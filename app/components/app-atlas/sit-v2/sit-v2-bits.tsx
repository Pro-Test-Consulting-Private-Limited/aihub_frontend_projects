"use client";

import { useState } from "react";
import { TbCheck, TbCopy, TbSparkles, TbTemplate, TbUser } from "react-icons/tb";

function fmtWhen(ms?: string | number) {
  if (!ms) return "";
  const n = typeof ms === "number" ? ms : Number(ms);
  if (!Number.isFinite(n) || n <= 0) return "";
  try {
    return new Date(n).toLocaleString(undefined, {
      day: "numeric",
      month: "short",
      hour: "2-digit",
      minute: "2-digit",
    });
  } catch {
    return "";
  }
}

export function provenanceTooltip(cells: Record<string, string>): string {
  const origin = (cells.origin || "ai").toLowerCase();
  const edited = cells.edited === "1" || cells.edited === "true";
  const parts: string[] = [];
  if (origin === "human") {
    parts.push(`Added by human${cells.editedBy ? ` ${cells.editedBy}` : ""}${fmtWhen(cells.editedAt) ? ` ${fmtWhen(cells.editedAt)}` : ""}`);
  } else if (origin === "template") {
    parts.push(`Legacy template row${fmtWhen(cells.editedAt) ? ` ${fmtWhen(cells.editedAt)}` : ""}`);
  } else {
    parts.push(`Generated by AI${fmtWhen(cells.generatedAt) ? ` ${fmtWhen(cells.generatedAt)}` : ""}`);
  }
  if (edited) {
    parts.push(
      `edited by ${cells.editedBy || "someone"}${fmtWhen(cells.editedAt) ? ` ${fmtWhen(cells.editedAt)}` : ""}`,
    );
    if (cells.aiOriginal) parts.push("original available");
  }
  return parts.join(", ");
}

/** Compact provenance icon for the ID cell (no Origin column). */
export function OriginGlyph({
  origin,
  edited,
  title,
}: {
  origin?: string;
  edited?: boolean;
  title?: string;
}) {
  // Edited dot only for AI rows (never human / legacy template).
  const showEdited = !!edited && origin !== "human" && origin !== "template";
  const tip =
    title ||
    (origin === "human" ? "Human" : origin === "template" ? "Legacy (old template row)" : "AI");
  if (origin === "human") {
    return (
      <span className="inline-flex items-center gap-0.5 text-[#1d4ed8]" title={tip} aria-label="Human">
        <TbUser size={12} />
      </span>
    );
  }
  if (origin === "template") {
    return (
      <span className="inline-flex items-center gap-0.5 text-[#6b7280]" title={tip} aria-label="Legacy">
        <TbTemplate size={12} />
      </span>
    );
  }
  return (
    <span className="inline-flex items-center gap-0.5 text-[#8664F2]" title={tip} aria-label="AI">
      <TbSparkles size={12} />
      {showEdited ? (
        <span className="h-1.5 w-1.5 rounded-full bg-[#d97706]" title="Edited — an AI row changed by a person" />
      ) : null}
    </span>
  );
}

/** Legacy labelled badge (drawer / legend). */
